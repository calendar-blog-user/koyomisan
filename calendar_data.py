#   15日周期: 大潮4日→中潮3日→小潮3日→長潮1日→若潮1日→中潮3日。朔(1日)と望(15日)から数え始める
#   海上保安庁の潮汐表(関門海峡海上交通センター掲載の月別表55日分)と照合して、48日が一致した(約87%)。
#   一致しない日は、旧暦10〜12日と15日の前後で、1日ずれていた。「大・中・小」の分類では52日が一致した
