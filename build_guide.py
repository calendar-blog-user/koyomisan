def build_nenjugyoji():
    fixed = []
    for r in jsonl("memorial_days.jsonl"):
        for x in r["entries"]:
            if x.get("category") == "年中行事":
                fixed.append((r["month"], r["day"], x["name"], x["origin"], x.get("major", False)))
    events = []
    for m, dd, name, origin, major in fixed:
        events.append((name, f"{m}月{dd}日", origin, major))
    names_found = set()
    d = date(2026, 1, 1)
    while d.year < 2036:
        for x in ce.events_on(d):
            names_found.add((x["name"], x.get("major", False), x["desc"]))
        d += timedelta(days=1)
    fixed_names = {x[0] for x in events}
    for name, major, desc in sorted(names_found):
        if name in fixed_names:
            continue
        base = name.split("（")[0]
        when = RULE_EVENT_WHEN.get(name) or RULE_EVENT_WHEN.get(base) or ""
        events.append((name, when, desc, major))
    # 日付順に並べるための補助(規則で決まるものは後ろ)
    def sortkey(x):
        w = x[1]
        import re
        m = re.match(r"(\d+)月(\d+)日", w)
        return (int(m.group(1)), int(m.group(2))) if m else (13, 0)
    events.sort(key=sortkey)
    body = _p("年中行事（ねんじゅうぎょうじ）は、毎年、決まった時期に行われる、季節の行事です。正月の七草や鏡開き、五節句（人日・上巳・端午・七夕・重陽）、お盆、冬至など、暮らしの中で受け継がれてきました。") + \
        _p("こよみさんでは、通知の対象になる「主要な年中行事」と、それ以外の行事（サイトにだけ表示）を、区別しています。") + _toc([x[0] for x in events])
    for name, when, desc, major in events:
        rows = [["日付", e(when) if when else "年によって異なります"], ["通知", "する（主要な年中行事）" if major else "しない（サイトにだけ表示）"]]
        body += _sec(name, "", _p(desc) + _table(["", ""], rows), "年中行事")
    write("nenjugyoji", "年中行事", "七草・鏡開き・節分・ひな祭り・端午・七夕・お盆・十五夜・冬至など、年中行事の由来の解説です。", body, ("shukujitsu", "saijitsu", "kinenbi", "zassetsu"))


def build_kinenbi():
    rows = []
    for r in jsonl("memorial_days.jsonl"):
        for x in r["entries"]:
            if x.get("category", "記念日") == "記念日":
                rows.append((r["month"], r["day"], x["name"], x["origin"]))
    rows.sort()
    seen, uniq = set(), []
    for m, dd, n, o in rows:
        if n in seen:
            continue
        seen.add(n); uniq.append((m, dd, n, o))
    body = _p("記念日は、「〇〇の日」のように、日付に由来や語呂合わせのある日です。こよみさんでは、由来が比較的はっきりしているものを、選んで載せています。") + \
        _p("記念日の由来には、複数の説があるものや、団体や企業が制定したものがあります。内容は、目安としてご覧ください。") + _toc([x[2] for x in uniq])
    for m, dd, n, o in uniq:
        body += _sec(n, "", _p(o) + _table(["", ""], [["日付", f"{m}月{dd}日"]]), "記念日")
    write("kinenbi", "記念日", "「〇〇の日」のように、日付に由来や語呂合わせのある記念日の解説です。", body, ("nenjugyoji", "shukujitsu"))


