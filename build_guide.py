    body = _toc([n for n, _ in cd.WAREKI_ERAS])
    for name, start in cd.WAREKI_ERAS:
        end = ends[name]
        span = f"{start.year}年{md(start)}〜" + (f"{end.year}年{md(end)}" if end else "（現在）")
        n_years = (end.year - start.year + 1) if end else None
