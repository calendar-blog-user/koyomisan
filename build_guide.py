def _sekki_order():
    return sorted(SEKKI_NAMES, key=lambda s: (s[2] - 315) % 360)


def _approx_md(lon, year=2026):
    """太陽黄経 lon になる日(日本時間)を、「◯月◯日」で返す。lonの季節に合わせて、探す起点を決める"""
    base = {315: (2, 4), 345: (3, 6), 0: (3, 21)}
    # 立春(315度)=2月4日ごろを基準に、黄経1度≒1.0146日として、起点を決める
    days = ((lon - 315) % 360) / 360 * 365.2422
    start = date(year, 2, 4) + timedelta(days=int(days) - 3)
    d = crossing_date(lon, start.year, start.month, start.day)
    return d


