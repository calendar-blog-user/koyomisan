def jsonl(name):
    with open(os.path.join(HERE, name), encoding="utf-8") as f:
        return [json.loads(l) for l in f if l.strip()]


def _jpdate(v):
    """date または '2030-12-31' のような文字列を「2030年12月31日」にする"""
    if isinstance(v, str):
        y, m, d = (int(x) for x in v.split("-"))
        v = date(y, m, d)
    return f"{v.year}年{v.month}月{v.day}日"


def md(d):
    return f"{d.month}月{d.day}日"


def crossing_date(lon, year, m, d):
    start = (datetime(year, m, d, tzinfo=JST) - timedelta(days=12)).astimezone(timezone.utc)
    return find_longitude_crossing(lon, start, search_days=45).astimezone(JST).date()


