def _p(*paras):
    return "".join(f"<p>{x}</p>" for x in paras)


def _toc(names):
    return '<nav class="toc" aria-label="目次">' + "".join(f'<a href="#{e(n)}">{e(n)}</a>' for n in names) + "</nav>"


def _sec(name, yomi="", body="", tag=""):
    t = f'<span class="tag">{e(tag)}</span>' if tag else ""
    y = f"<small>（{e(yomi)}）</small>" if yomi else ""
    return f'<section class="item" id="{e(name)}"><h2>{t}{e(name)}{y}</h2>{body}</section>\n'


def _table(head, rows, wide=False):
    th = "".join(f"<th>{e(h)}</th>" for h in head)
    tr = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    thead = f"<thead><tr>{th}</tr></thead>" if any(head) else ""
    t = f"<table>{thead}<tbody>{tr}</tbody></table>"
    return f'<div class="wide">{t}</div>' if wide else t


def _related(*slugs):
    return '<div class="card"><h3 style="margin-top:0">あわせて読みたい</h3><div class="rel">' + \
        "".join(f'<a href="{s}.html">{e(TITLE[s])}</a>' for s in slugs) + "</div></div>"


